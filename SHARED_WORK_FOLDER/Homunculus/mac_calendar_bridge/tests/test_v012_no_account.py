# TDD-6  watcher.main() — missing calendar → graceful exit, not crash loop
# ---------------------------------------------------------------------------

class TestWatcherMissingCalendarExitsGracefully:
    """
    If verify_calendar_exists returns False at startup, watcher.main() must:
      - Log the actionable error message.
      - Exit with sys.exit(1) or equivalent non-zero.
      - NOT enter the watch loop (no Observer started).
    """

    def test_exits_with_sysexit_when_calendar_missing(self):
        with (
            patch("mac_calendar_bridge.watcher.verify_calendar_exists", return_value=False),
            patch("mac_calendar_bridge.watcher.configure_logging"),
            patch("mac_calendar_bridge.watcher.cold_boot_sweep") as mock_sweep,
            pytest.raises(SystemExit) as exc_info,
        ):
            from mac_calendar_bridge.watcher import main
            main()

        assert exc_info.value.code != 0, "sys.exit must be non-zero when calendar is missing"
        mock_sweep.assert_not_called()

    def test_logs_actionable_message_when_calendar_missing(self, caplog):
        import logging
        with (
            patch("mac_calendar_bridge.watcher.verify_calendar_exists", return_value=False),
            patch("mac_calendar_bridge.watcher.configure_logging"),
            caplog.at_level(logging.ERROR, logger="mac_calendar_bridge.watcher"),
            pytest.raises(SystemExit),
        ):
            from mac_calendar_bridge.watcher import main
            main()

        combined = " ".join(caplog.messages)
        # The message must tell Thomas what to do
        assert "Create" in combined or "create" in combined or "iCloud" in combined, (
            f"Log message is not actionable. Got: {caplog.messages}"
        )

    def test_observer_not_started_when_calendar_missing(self):
        with (
            patch("mac_calendar_bridge.watcher.verify_calendar_exists", return_value=False),
            patch("mac_calendar_bridge.watcher.configure_logging"),
            patch("mac_calendar_bridge.watcher.Observer") as mock_observer_cls,
            pytest.raises(SystemExit),
        ):
            from mac_calendar_bridge.watcher import main
            main()

        # Observer must never have been instantiated or started
        mock_observer_cls.assert_not_called()


