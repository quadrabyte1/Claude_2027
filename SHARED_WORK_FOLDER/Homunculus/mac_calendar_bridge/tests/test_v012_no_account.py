# TDD-5  Regression guard — no tell account in any .py source file
# ---------------------------------------------------------------------------

class TestRegressionGuardNoTellAccount:
    """
    Static scan: zero occurrences of 'tell account' in any .py file under
    src/mac_calendar_bridge/. This catches the exact pattern that caused the
    v0.1.1 crash-loop and prevents it from ever returning.
    """

    def test_no_tell_account_in_source_tree(self):
        # Scan .py source for "tell account" on lines that are part of an
        # f-string (i.e., would be rendered into actual AppleScript at runtime).
        # Pure Python comment lines (# ...) and plain docstring prose are OK
        # because they document WHY the construct is invalid.
        # We flag: lines containing "tell account" AND an f-string opening
        # quote on the same line (pattern: f" or f').
        import re
        src_root = Path(__file__).parent.parent / "src" / "mac_calendar_bridge"
        violations = []
        for py_file in src_root.rglob("*.py"):
            content = py_file.read_text(encoding="utf-8")
            for lineno, line in enumerate(content.splitlines(), 1):
                stripped = line.strip()
                if "tell account" not in line:
                    continue
                # Skip pure comment lines
                if stripped.startswith("#"):
                    continue
                # Skip lines that have no f-string indicator
                # (prose in docstrings or module-level strings)
                if not re.search(r"\bf['\"]", line):
                    continue
                violations.append(f"{py_file}:{lineno}: {stripped}")

        assert not violations, (
            "REGRESSION: 'tell account' found inside an f-string in source. "
            "Calendar.app does not support this AppleScript construct. "
            "Remove it from:\n" + "\n".join(violations)
        )


