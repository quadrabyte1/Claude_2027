#!/bin/bash
# mac_calendar_bridge v0.1 install script
#
# Installs the bridge to the boot volume (required — repo lives on /Volumes/GIT
# which is nosuid; launchd cannot exec scripts from there).
#
# What this does:
#   1. Creates ~/.local/lib/mac_calendar_bridge/venv (Python venv on boot volume)
#   2. pip-installs mac-calendar-bridge (editable) from the repo
#   3. Writes ~/.local/bin/mac_calendar_bridge.sh (entry point)
#   4. Copies the launchd plist to ~/Library/LaunchAgents/ (macOS only)
#      - patches /Users/fourierflight → $HOME
#      - does NOT load the plist (you must grant Automation permission first)
#
# Usage:
#   bash deploy/install.sh [--venv-python /path/to/python3]
#
# On Linux the launchd section is skipped; nothing is installed automatically.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BRIDGE_REPO="$(dirname "$SCRIPT_DIR")"

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

BIN_DIR="${HOME}/.local/bin"
LIB_DIR="${HOME}/.local/lib/mac_calendar_bridge"
PLIST_SRC="${SCRIPT_DIR}/com.homunculus.mac_calendar_bridge.plist"
PLIST_DST="${HOME}/Library/LaunchAgents/com.homunculus.mac_calendar_bridge.plist"
VENV_PYTHON="${1:-python3}"

# Handle --venv-python flag
if [[ "${1:-}" == "--venv-python" && -n "${2:-}" ]]; then
    VENV_PYTHON="$2"
fi

# ---------------------------------------------------------------------------
# Create directories
# ---------------------------------------------------------------------------

mkdir -p "$BIN_DIR" "$LIB_DIR"
echo "[install] Created $BIN_DIR and $LIB_DIR"

# ---------------------------------------------------------------------------
# Create venv and install mac-calendar-bridge (editable)
# (boot volume so launchd can exec from here)
# ---------------------------------------------------------------------------

BRIDGE_VENV="${LIB_DIR}/venv"
if [ ! -d "$BRIDGE_VENV" ]; then
    echo "[install] Creating venv at $BRIDGE_VENV"
    "$VENV_PYTHON" -m venv "$BRIDGE_VENV"
fi

echo "[install] Installing mac-calendar-bridge into $BRIDGE_VENV"
"$BRIDGE_VENV/bin/pip" install --quiet -e "$BRIDGE_REPO"
echo "[install] Package installed."

# ---------------------------------------------------------------------------
# Write the entry-point shell script to ~/.local/bin/
# ---------------------------------------------------------------------------

ENTRY_SH="${BIN_DIR}/mac_calendar_bridge.sh"
cat > "$ENTRY_SH" <<'SHEOF'
#!/bin/bash
# Auto-generated by install.sh — do not edit by hand.
exec "${HOME}/.local/lib/mac_calendar_bridge/venv/bin/python" -m mac_calendar_bridge.watcher "$@"
SHEOF
chmod +x "$ENTRY_SH"
echo "[install] Entry point written to $ENTRY_SH"

# ---------------------------------------------------------------------------
# Install launchd plist (macOS only) — do NOT load it yet
# ---------------------------------------------------------------------------

if [[ "$(uname)" == "Darwin" ]]; then
    mkdir -p "${HOME}/Library/LaunchAgents"
    cp "$PLIST_SRC" "$PLIST_DST"
    # Patch the hardcoded /Users/fourierflight to the actual $HOME
    sed -i '' "s|/Users/fourierflight/|${HOME}/|g" "$PLIST_DST"
    echo "[install] Plist installed at $PLIST_DST"
    echo ""
    echo "======================================================================"
    echo "  IMPORTANT: Do not load the plist yet!"
    echo "  You must grant Automation permission FIRST."
    echo ""
    echo "  Steps:"
    echo "    1. Open System Settings → Privacy & Security → Automation"
    echo "    2. Find Terminal (or whichever app runs the bridge) and ensure"
    echo "       it has permission to control Calendar."
    echo "       — OR — load the plist once; macOS will prompt you automatically."
    echo "    3. Then run:"
    echo "       launchctl load $PLIST_DST"
    echo "    4. Confirm it started:"
    echo "       launchctl list | grep mac_calendar_bridge"
    echo "       tail -f /tmp/mac_calendar_bridge.log"
    echo ""
    echo "  See docs/FIRST_RUN.md for the full walkthrough."
    echo "======================================================================"
else
    echo ""
    echo "======================================================================"
    echo "  Linux detected — launchd is not available."
    echo ""
    echo "  The bridge is Mac-only (AppleScript / Calendar.app)."
    echo "  On Linux, Herman still works; only the Calendar sync is unavailable."
    echo "======================================================================"
fi

# ---------------------------------------------------------------------------
# Verify plutil (macOS only)
# ---------------------------------------------------------------------------

if [[ "$(uname)" == "Darwin" ]]; then
    if plutil -lint "$PLIST_DST" >/dev/null 2>&1; then
        echo "[install] plutil lint: OK"
    else
        echo "[install] WARNING: plutil found issues in the plist — check $PLIST_DST"
    fi
fi

echo ""
echo "[install] Done. See docs/FIRST_RUN.md for next steps."
